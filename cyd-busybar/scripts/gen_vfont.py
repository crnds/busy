def tiny_cols(art):
    """Column-major, bit 0 = top row."""
    cols = []
    for x in range(3):
        b = 0
        for y in range(5):
            if art[y][x] != ' ':
                b |= (1 << y)
        cols.append(b)
    return cols

def render(cols, h):
    for y in range(h):
        print(''.join('#' if (c >> y) & 1 else '.' for c in cols))

def main():
    assert len(F5x7) == 95, f"5x7 table has {len(F5x7)} entries, need 95"

    tiny = []
    for code in range(0x20, 0x7F):
        ch = chr(code)
        key = ch.upper() if ch.islower() else ch
        art = T3x5_SRC.get(key)
        if art is None:
            raise SystemExit(f"3x5 face is missing U+{code:04X} ({ch!r})")
        tiny.append(tiny_cols(art))
    assert len(tiny) == 95

    if '--show' in sys.argv:
        for ch in 'A0g%':
            print(f"--- 5x7 {ch!r} ---"); render(F5x7[ord(ch) - 0x20], 7)
            print(f"--- 3x5 {ch!r} ---"); render(tiny[ord(ch) - 0x20], 5)
        return

    out = []
    out.append("// GENERATED by scripts/gen_vfont.py -- do not edit by hand.")
    out.append("// Column-major, bit 0 = top row. ASCII 0x20..0x7E, 95 glyphs each.")
    out.append("")
    out.append("static const uint8_t VFONT_5X7[95][5] = {")
    for i, g in enumerate(F5x7):
        out.append("    {%s}, // 0x%02X %s" % (
            ",".join("0x%02X" % b for b in g), 0x20 + i,
            repr(chr(0x20 + i))))
    out.append("};")
    out.append("")
    out.append("static const uint8_t VFONT_3X5[95][3] = {")
    for i, g in enumerate(tiny):
        out.append("    {%s}, // 0x%02X %s" % (
            ",".join("0x%02X" % b for b in g), 0x20 + i,
            repr(chr(0x20 + i))))
    out.append("};")
    open("src/canvas/vfont.inc", "w").write("\n".join(out) + "\n")
    print("wrote src/canvas/vfont.inc: 95 + 95 glyphs")

    # The same two faces for simulator.html, so the simulated panels draw the
    # firmware's real glyphs rather than a browser font pretending to be them.
    import json
    js = "const VFONT = " + json.dumps(
        {"t3x5": [list(g) for g in tiny],
         "t5x7": [list(g) for g in F5x7]},
        separators=(",", ":")) + ";\n"
    open("scripts/sim_vfont.js", "w").write(js)
    print(f"wrote scripts/sim_vfont.js ({len(js)} bytes)")

main()
